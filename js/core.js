/* BioMetal Health — homepage v2, shared helpers.                                -z1n
   Owned by the orchestrator. Section agents call these; they do not edit this file. If a section
   needs something that is not here, it keeps its own helper inside its own section.js.

   window.BMH
     reduced                 true when prefers-reduced-motion: reduce. Show the settled frame.
     onScroll(fn)            fn({y, vh, vw}) once per animation frame while scrolling or resizing,
                             and once on registration. One shared listener for the whole page.
     pinProgress(el)         0..1 through a tall section that holds a sticky stage:
                             0 when el's top reaches the top of the viewport,
                             1 when el's bottom reaches the bottom of the viewport.
     passProgress(el)        0..1 as el passes through the viewport:
                             0 when el's top meets the viewport bottom, 1 when its bottom leaves the top.
     visible(el, fn)         fn(true|false) as el enters or leaves the viewport (with a margin).
                             Use it to stop rendering offscreen.
     bytes(id)               ArrayBuffer from an inlined <script type="application/octet-stream" id=...>.
     glb(id)                 Promise<gltf> parsed from one of those blobs with THREE.GLTFLoader.
     renderer(canvas, o)     a THREE.WebGLRenderer set up the same way everywhere
                             (sRGB out, ACES filmic, physically correct lights, alpha, DPR <= 2).
     studio(renderer)        a PMREM environment map from THREE.RoomEnvironment, for metal.
     knobs(name, defaults)   a section's KNOBS, with any overrides a review board injected
                             (window.BMH_KNOBS = { hero: {...} }) merged over them. No board, no change.
     look                    'dark' or 'light': the site's look (28 Sep). The main site is 'dark', meaning it keeps
                             the three dark x-ray treatments Andrew asked for (the Technology and Opportunity
                             heroes, Technology's property columns); 'light' makes those light too.
                             build.py --look light writes <html data-look="light">; a board can set
                             window.BMH_KNOBS = { site: { look: 'light' } }. Either way core.js puts it on
                             <html data-look>, which the sections' CSS keys on, and it is their knobs' default.
     color(hex)              a hex colour for a three.js material, converted from sRGB (r147 reads hex as linear).
     METAL                   the two surface states of the real parts, from model-*-z1n/SPEC.md §7.
     PLATE_V2                the measured plate every section draws (glb-plate-v2-hi). No reshape.
     PLATE, plateReshape(g)  v1 stopgap, for plate-hi.glb only. Never on v2.
     clamp, lerp, smooth(e0, e1, x), ease(x)   small maths. */
(function () {
  'use strict';
  var BMH = (window.BMH = window.BMH || {});

  BMH.reduced = !!(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches);

  var site = (window.BMH_KNOBS || {}).site || {};
  BMH.look = (site.look || document.documentElement.getAttribute('data-look')) === 'light' ? 'light' : 'dark';
  document.documentElement.setAttribute('data-look', BMH.look);

  BMH.clamp = function (x, a, b) { return x < a ? a : x > b ? b : x; };
  BMH.lerp = function (a, b, t) { return a + (b - a) * t; };
  BMH.smooth = function (e0, e1, x) { var t = BMH.clamp((x - e0) / (e1 - e0), 0, 1); return t * t * (3 - 2 * t); };
  BMH.ease = function (x) { return 1 - Math.pow(1 - BMH.clamp(x, 0, 1), 3); };

  /* ---- one scroll loop for the page ---- */
  var subs = [], queued = false;
  function tick() {
    queued = false;
    var st = { y: window.scrollY || window.pageYOffset, vh: window.innerHeight, vw: window.innerWidth };
    for (var i = 0; i < subs.length; i++) subs[i](st);
  }
  function queue() { if (!queued) { queued = true; requestAnimationFrame(tick); } }
  window.addEventListener('scroll', queue, { passive: true });
  window.addEventListener('resize', queue);
  BMH.onScroll = function (fn) { subs.push(fn); queue(); };

  BMH.pinProgress = function (el) {
    var r = el.getBoundingClientRect(), vh = window.innerHeight, span = r.height - vh;
    return span <= 0 ? (r.top <= 0 ? 1 : 0) : BMH.clamp(-r.top / span, 0, 1);
  };
  BMH.passProgress = function (el) {
    var r = el.getBoundingClientRect(), vh = window.innerHeight;
    return BMH.clamp((vh - r.top) / (vh + r.height), 0, 1);
  };

  BMH.visible = function (el, fn, margin) {
    if (!('IntersectionObserver' in window)) { fn(true); return; }
    new IntersectionObserver(function (es) { fn(es[0].isIntersecting); }, { rootMargin: margin || '20% 0px' }).observe(el);
  };

  /* ---- inlined binary assets ---- */
  var cache = {};
  BMH.bytes = function (id) {
    if (cache[id]) return cache[id];
    var el = document.getElementById(id);
    if (!el) throw new Error('BMH.bytes: no blob #' + id);
    var bin = atob(el.textContent.trim()), n = bin.length, u = new Uint8Array(n);
    for (var i = 0; i < n; i++) u[i] = bin.charCodeAt(i);
    return (cache[id] = u.buffer);
  };
  BMH.glb = function (id) {   /* Webflow source: an empty blob with data-src loads that file */
    var el = document.getElementById(id), url = el && !el.textContent.trim() && el.getAttribute('data-src');
    var buf = url ? fetch(url).then(function (r) { return r.arrayBuffer(); }) : Promise.resolve(BMH.bytes(id));
    return buf.then(function (bytes) {
      return new Promise(function (res, rej) { new THREE.GLTFLoader().parse(bytes, '', res, rej); });
    });
  };

  /* ---- three.js, set up the same way in every section ---- */
  BMH.renderer = function (canvas, o) {
    o = o || {};
    var r = new THREE.WebGLRenderer({ canvas: canvas, antialias: true, alpha: o.alpha !== false, powerPreference: 'high-performance' });
    r.setPixelRatio(Math.min(window.devicePixelRatio || 1, o.maxDpr || 2));
    r.outputEncoding = THREE.sRGBEncoding;
    r.toneMapping = THREE.ACESFilmicToneMapping;
    r.toneMappingExposure = o.exposure || 1.0;
    r.physicallyCorrectLights = true;
    if (o.shadows) { r.shadowMap.enabled = true; r.shadowMap.type = THREE.PCFSoftShadowMap; }
    return r;
  };
  BMH.studio = function (renderer) {
    var pm = new THREE.PMREMGenerator(renderer);
    var tex = pm.fromScene(new THREE.RoomEnvironment(), 0.04).texture;
    pm.dispose();
    return tex;
  };

  /* The real parts' two states (model-plate-z1n/SPEC.md §7, identical for the screw).
     Uncoated is machined metal; coated is 17% brighter, a hair cooler, tighter highlights.
     These are the baseline. A section may push the difference for legibility; if it does, it
     says so in its report so the integration pass can make every section agree. */
  /* r147 reads new THREE.Color('#hex') as LINEAR, so a hex written from a design token or a spec renders
     brighter than it should under sRGB output. BMH.color('#hex') converts it properly. Use it for every
     hex colour handed to a three.js material, including BMH.METAL's. A GLB's own materials are already right. */
  /* Review boards (tools/board.py) build one section once and show it several ways side by side. They set
     window.BMH_KNOBS before this file loads; every section declares its KNOBS through here. */
  BMH.knobs = function (name, defaults) {
    var o = (window.BMH_KNOBS || {})[name];
    if (o) for (var k in o) if (Object.prototype.hasOwnProperty.call(o, k)) defaults[k] = o[k];
    return defaults;
  };
  BMH.color = function (hex) { return new THREE.Color(hex).convertSRGBToLinear(); };

  BMH.METAL = {
    uncoated: { color: '#cbced1', metalness: 1.0, roughness: 0.43 },
    coated:   { color: '#dadde0', metalness: 1.0, roughness: 0.24 }
  };

  /* ---- the plate, drawn the same in every section (lifted from 01-hero, 2026-09-25) ----
     BMH.plateReshape(geometry, o) takes plate-hi.glb's mesh geometry (metres) and returns a new
     geometry adjusted toward the Swanson photographs:
       - the walls grow to o.thicknessMm (GLB 1.00 mm, photos read nearer 2 mm), 0.18 mm fillets kept;
       - each countersink becomes a crisp o.countersinkDeg cone, o.countersinkMm across at the top
         face, with a real bore wall under it (the GLB's is one smooth-shaded soft dish).
     Returns { geometry, holes, yc, Rt } — holes=false means the mesh wasn't the expected one and
     only the thickness changed; yc/Rt (mm) are the cone's bottom height and top radius, which the
     hero's shader uses. Use plate-hi.glb (blob id glb-plate-hi); the vertex tests expect it. */
  /* THE PLATE IS NOW v2 (2026-09-25): ASSETS/3d/plate-v2-hi.glb, blob id glb-plate-v2-hi, measured from
     BioMetal's photographs (prototype-z1n/model-plate-v2-z1n/SPEC.md). It already has the measured
     thickness and crisp countersinks. NEVER run plateReshape on it: it would make it 2.8 mm thick.
     plateReshape below is kept only for v1's plate-hi.glb. Every section reads v2's numbers from here. */
  BMH.PLATE_V2 = {
    blob: 'glb-plate-v2-hi',
    lengthMm: 57.786, widthMm: 9.068, thicknessMm: 1.815,        // X, Z, +Y (seating face at Y = 0)
    holesXmm: [-24.359, -12.124, 12.124, 24.359],                  // hole centres along X, Z = 0
    coneBottomYmm: 1.280, coneTopRmm: 3.194, boreRmm: 2.165,      // countersink cone and straight bore
    materials: ['biometal_uncoated', 'biometal_coated']           // same names and switch as v1
  };
  BMH.PLATE = { thicknessMm: 2.0, countersinkMm: 7.2, countersinkDeg: 90 };   // v1 stopgap only
  BMH.plateReshape = function (src, o) {
    o = o || BMH.PLATE;
    var DEG = Math.PI / 180;
    var T = o.thicknessMm, Rt = o.countersinkMm / 2, half = o.countersinkDeg / 2 * DEG;
    var HOLES = [-18.0, -9.29, 9.29, 18.0];
    var P = src.attributes.position, Nn = src.attributes.normal, UV = src.attributes.uv;
    var n = P.count, idx = src.index.array;
    var ring = new Int8Array(n), cx = new Float32Array(n);
    var c1 = 0, c2 = 0, c3 = 0, i, k;
    for (i = 0; i < n; i++) {
      var x0 = P.getX(i) * 1000, y0 = P.getY(i) * 1000, z0 = P.getZ(i) * 1000;
      var h = HOLES[0];
      for (k = 1; k < 4; k++) if (Math.abs(x0 - HOLES[k]) < Math.abs(x0 - h)) h = HOLES[k];
      var r0 = Math.hypot(x0 - h, z0);
      cx[i] = h;
      if (r0 > 3.9 && r0 < 4.1 && Math.abs(y0 - 1.0) < 0.003) { ring[i] = 3; c3++; }
      else if (r0 < 2.6 && Math.abs(y0 - 0.1615) < 0.01) { ring[i] = 2; c2++; }
      else if (r0 < 2.6 && Math.abs(y0 - 0.079) < 0.006) { ring[i] = 1; c1++; }
    }
    var holes = c1 > 0 && c1 === c2 && c2 === c3;
    var rD = 2.5476, dr = Rt - rD, depth = dr / Math.tan(half), yc = T - depth;
    var nl = Math.hypot(depth, dr), ny = dr / nl, nr = -depth / nl;

    /* cone triangles get their own copies of the top-edge vertices, so the edge is crisp */
    var dup = new Map(), newIdx = new Uint32Array(idx.length), extra = 0;
    for (var t = 0; t < idx.length; t += 3) {
      var tri = [idx[t], idx[t + 1], idx[t + 2]];
      var cone = holes && (ring[tri[0]] === 2 || ring[tri[1]] === 2 || ring[tri[2]] === 2) &&
                          (ring[tri[0]] === 3 || ring[tri[1]] === 3 || ring[tri[2]] === 3);
      for (k = 0; k < 3; k++) {
        var v = tri[k];
        if (cone && ring[v] === 3) {
          if (!dup.has(v)) dup.set(v, n + extra++);
          newIdx[t + k] = dup.get(v);
        } else newIdx[t + k] = v;
      }
    }
    var m = n + extra;
    var pos = new Float32Array(m * 3), nor = new Float32Array(m * 3), uv = new Float32Array(m * 2);
    for (i = 0; i < n; i++) {
      var x = P.getX(i) * 1000, y = P.getY(i) * 1000, z = P.getZ(i) * 1000;
      var nx = Nn.getX(i), nyy = Nn.getY(i), nz = Nn.getZ(i);
      var r = Math.hypot(x - cx[i], z) || 1, ux = (x - cx[i]) / r, uz = z / r;
      if (holes && ring[i] === 3) { x = cx[i] + ux * Rt; z = uz * Rt; y = T; }
      else if (holes && ring[i] === 2) { y = yc; nx = ux * nr; nyy = ny; nz = uz * nr; }
      else if (holes && ring[i] === 1) { y = yc - 0.0825; }
      else if (y > 0.5) y += T - 1;
      pos[i * 3] = x / 1000; pos[i * 3 + 1] = y / 1000; pos[i * 3 + 2] = z / 1000;
      nor[i * 3] = nx; nor[i * 3 + 1] = nyy; nor[i * 3 + 2] = nz;
      if (UV) { uv[i * 2] = UV.getX(i); uv[i * 2 + 1] = UV.getY(i); }
    }
    dup.forEach(function (j, i2) {
      pos[j * 3] = pos[i2 * 3]; pos[j * 3 + 1] = pos[i2 * 3 + 1]; pos[j * 3 + 2] = pos[i2 * 3 + 2];
      var xx = pos[i2 * 3] * 1000, zz = pos[i2 * 3 + 2] * 1000, rr = Math.hypot(xx - cx[i2], zz) || 1;
      nor[j * 3] = (xx - cx[i2]) / rr * nr; nor[j * 3 + 1] = ny; nor[j * 3 + 2] = zz / rr * nr;
      uv[j * 2] = uv[i2 * 2]; uv[j * 2 + 1] = uv[i2 * 2 + 1];
    });
    var g = new THREE.BufferGeometry();
    g.setAttribute('position', new THREE.BufferAttribute(pos, 3));
    g.setAttribute('normal', new THREE.BufferAttribute(nor, 3));
    if (UV) g.setAttribute('uv', new THREE.BufferAttribute(uv, 2));
    g.setIndex(new THREE.BufferAttribute(newIdx, 1));
    g.computeBoundingSphere();
    g.computeBoundingBox();
    return { geometry: g, holes: holes, yc: holes ? yc : 0.08, Rt: holes ? Rt : 4.0 };
  };

  /* ---- nav: solid once the page moves; menu toggle under 900px ---- */
  document.addEventListener('DOMContentLoaded', function () {
    var nav = document.querySelector('.nav');
    if (!nav) return;
    BMH.onScroll(function (st) { nav.classList.toggle('is-scrolled', st.y > 8); });
    var btn = nav.querySelector('.nav__menu');
    if (btn) btn.addEventListener('click', function () {
      var open = nav.classList.toggle('is-open');
      btn.setAttribute('aria-expanded', open ? 'true' : 'false');
    });
  });
})();
