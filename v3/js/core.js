/* BioMetal Health — site v3, shared helpers.                                       -z1n
   Owned by the orchestrator. Section agents call these; they do not edit this file. If a section
   needs something that is not here, it keeps its own helper inside its own section.js.

   v3 (4 Nov, PLAN.md §7 WP1b, Phase 0): the Webflow build's speed helpers of 17 Oct
   (webflow-v2-z1n/build/site-code/core.js, perf/AUDIT.md directives 2-4) ported back: BMH.rect, BMH.vh,
   BMH.idle, BMH.busy, BMH.afterLoad, BMH.warm, BMH.PHONE_MQ, the model queue, the newest-entry
   BMH.visible and BMH.renderer's antialias switch. v3 keeps its inline loader: models are blobs in the
   page, not files fetched by URL. Every existing call keeps its meaning.

   window.BMH
     reduced                 true when prefers-reduced-motion: reduce. Show the settled frame.
     onScroll(fn)            fn({y, vh, vw}) once per animation frame while scrolling or resizing,
                             and once on registration. One shared listener for the whole page.
     pinProgress(el)         0..1 through a tall section that holds a sticky stage:
                             0 when el's top reaches the top of the viewport,
                             1 when el's bottom reaches the bottom of the viewport.
     passProgress(el)        0..1 as el passes through the viewport:
                             0 when el's top meets the viewport bottom, 1 when its bottom leaves the top.
     rect(el)                el.getBoundingClientRect(), read once per frame: inside an onScroll callback it returns the
                             box measured at the start of that tick, before any section wrote a style (no forced
                             layout). The first time an element is asked for inside a tick, and on a tick where the
                             viewport size changed, it reads live; outside onScroll callbacks it always reads live.
                             pinProgress and passProgress read through it. Treat the box as read-only.
     vh()                    window.innerHeight, read once per tick the same way (innerHeight forces layout too).
     visible(el, fn, margin) fn(true|false) as el enters or leaves the viewport (default margin '20% 0px').
                             Use it to stop rendering offscreen. Each call passes the newest state (the last entry
                             of the observer's batch), so a stale entry never wins.
     idle(fn, o)             a Promise of fn(), run when the page is quiet: no busy() promise pending, no scroll for
                             150 ms, in an idle period, one job per period, first in first out. For building,
                             compiling and first-drawing 3D scenes. A job that has waited o.by ms (default 4000) runs at
                             the next idle period even during a scroll or a busy() hold; { by: 0 } never waits for them.
     busy(promise)           hold idle work until promise settles (6 s at most). Returns the promise.
                             The Home hero holds it for its entrance.
     afterLoad(fn)           idle(fn) after the window load event: for scenes nothing on screen needs yet.
     warm(renderer, scene, camera)   renderer.compile + one renderer.render, before the scene's first visible frame.
     PHONE_MQ                '(max-width: 900px)': v3's phone layout switch, for engines ported from Webflow (which
                             switch at 991 px). matchMedia(BMH.PHONE_MQ).
     bytes(id)               ArrayBuffer from an inlined <script type="application/octet-stream" id=...>.
     glb(id)                 Promise<gltf> from one of those blobs. Each blob is parsed once (THREE.GLTFLoader), in an
                             idle period, one at a time, in the order first asked for; every call gets its own copy of
                             the parsed scene (its own nodes, geometries and materials; the textures are shared, so
                             treat them as read-only). A missing or bad blob rejects, and a later call tries again.
     renderer(canvas, o)     a THREE.WebGLRenderer set up the same way everywhere
                             (sRGB out, ACES filmic, physically correct lights, alpha, DPR <= 2).
                             o.antialias false: no canvas multisampling, for scenes that finish with a full-screen pass
                             from their own multisampled target. Default true.
     studio(renderer)        a PMREM environment map from THREE.RoomEnvironment, for metal.
     knobs(name, defaults)   a section's KNOBS, with any overrides a review board injected
                             (window.BMH_KNOBS = { hero: {...} }) merged over them. No board, no change.
     look                    'dark' or 'light': the site's look (28 Sep). The main site is 'dark', meaning it keeps
                             the three dark x-ray treatments Andrew asked for (the Technology and Opportunity
                             heroes, Technology's property columns); 'light' makes those light too.
                             build.py --look light writes <html data-look="light">; a board can set
                             window.BMH_KNOBS = { site: { look: 'light' } }. Either way core.js puts it on
                             <html data-look>, which the sections' CSS keys on, and it is their knobs' default.
     color(hex)              a hex colour for a three.js material, converted from sRGB (r147 reads hex as linear).
     METAL                   the two surface states of the real parts, from model-*-z1n/SPEC.md §7.
     PLATE_V2                the measured plate every section draws (glb-plate-v2-hi). No reshape.
     PLATE, plateReshape(g)  v1 stopgap, for plate-hi.glb only. Never on v2.
     clamp, lerp, smooth(e0, e1, x), ease(x)   small maths.

   The nav (bottom of this file): solid once the page moves; the menu below 1000 px.
   Knobs 'nav': { news: true }; false takes the News item out of the bar (the footers still link the page). */
(function () {
  'use strict';
  var BMH = (window.BMH = window.BMH || {});

  BMH.reduced = !!(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches);

  var site = (window.BMH_KNOBS || {}).site || {};
  BMH.look = (site.look || document.documentElement.getAttribute('data-look')) === 'light' ? 'light' : 'dark';
  document.documentElement.setAttribute('data-look', BMH.look);

  /* v3's phone layout, for the engines ported from Webflow (PLAN.md §2, phone pose rule): wherever a Webflow file
     says (max-width: 991px), v3 says this; wherever it says 767, v3 says 760 */
  BMH.PHONE_MQ = '(max-width: 900px)';

  BMH.clamp = function (x, a, b) { return x < a ? a : x > b ? b : x; };
  BMH.lerp = function (a, b, t) { return a + (b - a) * t; };
  BMH.smooth = function (e0, e1, x) { var t = BMH.clamp((x - e0) / (e1 - e0), 0, 1); return t * t * (3 - 2 * t); };
  BMH.ease = function (x) { return 1 - Math.pow(1 - BMH.clamp(x, 0, 1), 3); };

  /* ---- one scroll loop for the page ----
     Speed (Webflow, 17 Oct, perf/AUDIT.md site-core-tick-reads): every box a section reads through BMH.rect
     (pinProgress and passProgress included) is measured once at the start of the tick, before any subscriber writes a
     style, so no read inside the tick forces a style recalc and layout. Same values as before: the boxes read this way
     are sections, tracks and stages, which scroll-linked writes (transforms, opacity, colours) don't move. A tick where
     the viewport size changed reads live, so a section that resizes its track in that tick still sees the new box. */
  var subs = [], queued = false, inTick = false, lastW = -1, lastH = -1, lastScrollAt = -1e9, tickVH = 0;
  var boxes = new Map();                            /* el -> the box measured at the start of this tick (or null) */
  function tick() {
    queued = false;
    if (!subs.length) return;
    var st = { y: window.scrollY || window.pageYOffset, vh: window.innerHeight, vw: window.innerWidth };
    var same = st.vw === lastW && st.vh === lastH;
    lastW = st.vw; lastH = st.vh; tickVH = st.vh;
    boxes.forEach(function (r, el) { boxes.set(el, same && el.isConnected ? el.getBoundingClientRect() : null); });
    inTick = true;
    try { for (var i = 0; i < subs.length; i++) subs[i](st); }
    finally { inTick = false; }
  }
  function queue() { if (!queued) { queued = true; requestAnimationFrame(tick); } }
  window.addEventListener('scroll', function () { lastScrollAt = performance.now(); queue(); }, { passive: true });
  window.addEventListener('resize', queue);
  BMH.onScroll = function (fn) { subs.push(fn); queue(); };

  BMH.rect = function (el) {
    var r = boxes.get(el);
    if (r === undefined) boxes.set(el, null);
    return inTick && r ? r : el.getBoundingClientRect();
  };
  /* the viewport height, read once per tick too: window.innerHeight forces a style and layout pass of its own when
     a section has just written a style */
  BMH.vh = function () { return inTick ? tickVH : window.innerHeight; };
  BMH.pinProgress = function (el) {
    var r = BMH.rect(el), vh = BMH.vh(), span = r.height - vh;
    return span <= 0 ? (r.top <= 0 ? 1 : 0) : BMH.clamp(-r.top / span, 0, 1);
  };
  BMH.passProgress = function (el) {
    var r = BMH.rect(el), vh = BMH.vh();
    return BMH.clamp((vh - r.top) / (vh + r.height), 0, 1);
  };

  /* ---- quiet-time work (Webflow, 17 Oct, perf/AUDIT.md site-core-3d-helpers) ----
     BMH.idle(fn, o)  run fn when the page is quiet: no BMH.busy promise pending, no scroll for 150 ms, in an idle
                      period (requestIdleCallback, 1 s timeout; setTimeout where it is missing), one job per period, in
                      the order queued. A job that has waited o.by ms (default 4000) runs at the next idle period even
                      during a scroll or a busy hold. Returns a Promise of fn's result (a throw rejects it).
     BMH.busy(p)      hold the queue until promise p settles, or 6 s at most (the hero passes its entrance).
     BMH.afterLoad(fn) BMH.idle(fn) once the window load event has fired: for scenes nothing on screen needs yet.
     BMH.warm(renderer, scene, camera)  compile every material, then draw the scene once into the current target, so
                      programs (shadow-map ones too), geometry and textures are on the GPU before the first frame a
                      person sees. Call it while the canvas is off screen, with the scene posed as it will first show. */
  var jobs = [], holds = [], pumping = false;
  var idleCall = window.requestIdleCallback ? function (f) { window.requestIdleCallback(f, { timeout: 1000 }); } : function (f) { setTimeout(f, 50); };
  function pump() {
    if (pumping || !jobs.length) return;
    pumping = true;
    idleCall(function () {
      pumping = false;
      if (!jobs.length) return;
      var now = performance.now(), job = jobs[0];
      var wait = holds.length > 0 || now - lastScrollAt < 150;
      if (wait && now - job.at < job.by) { setTimeout(pump, 120); return; }
      jobs.shift();
      try { job.ok(job.fn()); } catch (e) { job.no(e); }
      pump();
    });
  }
  BMH.idle = function (fn, o) {
    return new Promise(function (ok, no) {
      jobs.push({ fn: fn, ok: ok, no: no, at: performance.now(), by: o && typeof o.by === 'number' ? o.by : 4000 });
      pump();
    });
  };
  BMH.busy = function (p) {
    var done = false;
    function release() { if (done) return; done = true; var i = holds.indexOf(p); if (i > -1) holds.splice(i, 1); pump(); }
    holds.push(p);
    Promise.resolve(p).then(release, release);
    setTimeout(release, 6000);
    return p;
  };
  BMH.afterLoad = function (fn) {
    return new Promise(function (ok, no) {
      function go() { BMH.idle(fn).then(ok, no); }
      if (document.readyState === 'complete') go(); else window.addEventListener('load', go, { once: true });
    });
  };
  BMH.warm = function (renderer, scene, camera) {
    renderer.compile(scene, camera);
    renderer.render(scene, camera);
  };

  /* Webflow QA r21 (17 Oct): fn gets the NEWEST entry of each callback. One callback can carry two entries for el when
     two rendering updates land before the notify task (a busy main thread, the reader crossing the margin and back);
     the first is then stale, and reading it left a section's flag wrong until the next crossing. */
  BMH.visible = function (el, fn, margin) {
    if (!('IntersectionObserver' in window)) { fn(true); return; }
    new IntersectionObserver(function (es) { fn(es[es.length - 1].isIntersecting); }, { rootMargin: margin || '20% 0px' }).observe(el);
  };

  /* ---- inlined binary assets ---- */
  var cache = {};
  BMH.bytes = function (id) {
    if (cache[id]) return cache[id];
    var el = document.getElementById(id);
    if (!el) throw new Error('BMH.bytes: no blob #' + id);
    var bin = atob(el.textContent.trim()), n = bin.length, u = new Uint8Array(n);
    for (var i = 0; i < n; i++) u[i] = bin.charCodeAt(i);
    return (cache[id] = u.buffer);
  };

  /* ---- the models: each blob parsed once, then copied for every caller ----
     Before v3 every BMH.glb call decoded and parsed its blob again, at once: on Home the plate four times, all of it at
     DOMContentLoaded, in the hero's first frames. Now (the Webflow model queue of 17 Oct, perf/AUDIT.md
     site-core-glb-queue, with v3's inline loader in place of its download):
     - one parse per blob per page, in an idle period (200 ms timeout), one at a time, in the order first asked for, so
       the first scene's model comes first. It never waits for BMH.busy or a scroll: the scene that holds busy (the
       Home hero) needs its own model first, and the scenes' builds and compiles are what BMH.idle holds back;
     - the parsed original is never handed out. Each call gets a copy of its scene graph with its own geometries and
       materials, as a fresh parse gave before, so a section that re-parents, rescales or re-materials its copy (Home 04
       does) changes nothing anyone else holds. The textures (the finish maps) are shared: treat them as read-only;
     - once a blob is parsed its decoded bytes are let go (the parse holds what it needs); BMH.bytes still works. */
  var models = {}, line = Promise.resolve();
  var idleSlot = window.requestIdleCallback
    ? function () { return new Promise(function (go) { window.requestIdleCallback(function () { go(); }, { timeout: 200 }); }); }
    : function () { return new Promise(function (go) { setTimeout(go, 16); }); };
  function parse(id) {
    return new Promise(function (res, rej) {
      /* Webflow: an empty blob with data-src loads that file (the handoff's one change from the site's own build) */
      var el = document.getElementById(id), url = el && !el.textContent.trim() && el.getAttribute('data-src');
      (url ? fetch(url).then(function (r) { if (!r.ok) throw new Error('BMH.glb: ' + r.status + ' ' + url); return r.arrayBuffer(); })
           : Promise.resolve().then(function () { return BMH.bytes(id); }))
        .then(function (buf) { new THREE.GLTFLoader().parse(buf, '', res, rej); }, rej);
    });
  }
  function copyOf(g) {
    var geos = new Map(), mats = new Map();
    function mat(m) { if (!mats.has(m)) mats.set(m, m.clone()); return mats.get(m); }
    function deep(s) {
      var c = s.clone(true);
      c.traverse(function (o) {
        if (o.geometry) {
          if (!geos.has(o.geometry)) geos.set(o.geometry, o.geometry.clone());
          o.geometry = geos.get(o.geometry);
        }
        if (o.material) o.material = Array.isArray(o.material) ? o.material.map(mat) : mat(o.material);
      });
      return c;
    }
    var scenes = (g.scenes || [g.scene]).map(deep);
    var k = (g.scenes || []).indexOf(g.scene);
    return {
      scene: k > -1 ? scenes[k] : deep(g.scene), scenes: scenes,
      animations: g.animations, cameras: g.cameras, asset: g.asset, parser: g.parser, userData: g.userData
    };
  }
  BMH.glb = function (id) {
    var m = models[id];
    if (!m) {
      m = models[id] = line.then(idleSlot).then(function () { return parse(id); });
      line = m.then(function () { delete cache[id]; }, function () {});
      m.catch(function () { if (models[id] === m) delete models[id]; });
    }
    return m.then(copyOf);
  };

  /* ---- three.js, set up the same way in every section ---- */
  BMH.renderer = function (canvas, o) {
    o = o || {};
    /* o.antialias (Webflow, 17 Oct, perf/AUDIT.md site-core-3d-helpers): false for a scene whose final picture is a
       full-screen post pass from its own multisampled target (the canvas's multisampling can't change that picture).
       Default true. */
    var r = new THREE.WebGLRenderer({ canvas: canvas, antialias: o.antialias !== false, alpha: o.alpha !== false, powerPreference: 'high-performance' });
    r.setPixelRatio(Math.min(window.devicePixelRatio || 1, o.maxDpr || 2));
    r.outputEncoding = THREE.sRGBEncoding;
    r.toneMapping = THREE.ACESFilmicToneMapping;
    r.toneMappingExposure = o.exposure || 1.0;
    r.physicallyCorrectLights = true;
    if (o.shadows) { r.shadowMap.enabled = true; r.shadowMap.type = THREE.PCFSoftShadowMap; }
    return r;
  };
  BMH.studio = function (renderer) {
    var pm = new THREE.PMREMGenerator(renderer);
    var tex = pm.fromScene(new THREE.RoomEnvironment(), 0.04).texture;
    pm.dispose();
    return tex;
  };

  /* The real parts' two surface states (model-plate-z1n/SPEC.md §7, identical for the screw). The first is the
     machined metal; the second is 17% brighter, a hair cooler, with tighter highlights. These are the baseline. A
     section may push the difference for legibility; if it does, it says so in its report so the integration pass can
     make every section agree. The keys follow the GLB's own material names, which stay until the next export
     (PLAN.md §3.9). */
  /* r147 reads new THREE.Color('#hex') as LINEAR, so a hex written from a design token or a spec renders
     brighter than it should under sRGB output. BMH.color('#hex') converts it properly. Use it for every
     hex colour handed to a three.js material, including BMH.METAL's. A GLB's own materials are already right. */
  /* Review boards (tools/board.py) build one section once and show it several ways side by side. They set
     window.BMH_KNOBS before this file loads; every section declares its KNOBS through here. */
  BMH.knobs = function (name, defaults) {
    var o = (window.BMH_KNOBS || {})[name];
    if (o) for (var k in o) if (Object.prototype.hasOwnProperty.call(o, k)) defaults[k] = o[k];
    return defaults;
  };
  BMH.color = function (hex) { return new THREE.Color(hex).convertSRGBToLinear(); };

  BMH.METAL = {
    uncoated: { color: '#cbced1', metalness: 1.0, roughness: 0.43 },
    coated:   { color: '#dadde0', metalness: 1.0, roughness: 0.24 }
  };

  /* ---- the plate, drawn the same in every section (lifted from 01-hero, 2026-09-25) ----
     BMH.plateReshape(geometry, o) takes plate-hi.glb's mesh geometry (metres) and returns a new
     geometry adjusted toward the Swanson photographs:
       - the walls grow to o.thicknessMm (GLB 1.00 mm, photos read nearer 2 mm), 0.18 mm fillets kept;
       - each countersink becomes a crisp o.countersinkDeg cone, o.countersinkMm across at the top
         face, with a real bore wall under it (the GLB's is one smooth-shaded soft dish).
     Returns { geometry, holes, yc, Rt } — holes=false means the mesh wasn't the expected one and
     only the thickness changed; yc/Rt (mm) are the cone's bottom height and top radius, which the
     hero's shader uses. Use plate-hi.glb (blob id glb-plate-hi); the vertex tests expect it. */
  /* THE PLATE IS NOW v2 (2026-09-25): ASSETS/3d/plate-v2-hi.glb, blob id glb-plate-v2-hi, measured from
     BioMetal's photographs (prototype-z1n/model-plate-v2-z1n/SPEC.md). It already has the measured
     thickness and crisp countersinks. NEVER run plateReshape on it: it would make it 2.8 mm thick.
     plateReshape below is kept only for v1's plate-hi.glb. Every section reads v2's numbers from here. */
  BMH.PLATE_V2 = {
    blob: 'glb-plate-v2-hi',
    lengthMm: 57.786, widthMm: 9.068, thicknessMm: 1.815,        // X, Z, +Y (seating face at Y = 0)
    holesXmm: [-24.359, -12.124, 12.124, 24.359],                  // hole centres along X, Z = 0
    coneBottomYmm: 1.280, coneTopRmm: 3.194, boreRmm: 2.165,      // countersink cone and straight bore
    materials: ['biometal_uncoated', 'biometal_coated']           // the GLB's material names, as in v1
  };
  BMH.PLATE = { thicknessMm: 2.0, countersinkMm: 7.2, countersinkDeg: 90 };   // v1 stopgap only
  BMH.plateReshape = function (src, o) {
    o = o || BMH.PLATE;
    var DEG = Math.PI / 180;
    var T = o.thicknessMm, Rt = o.countersinkMm / 2, half = o.countersinkDeg / 2 * DEG;
    var HOLES = [-18.0, -9.29, 9.29, 18.0];
    var P = src.attributes.position, Nn = src.attributes.normal, UV = src.attributes.uv;
    var n = P.count, idx = src.index.array;
    var ring = new Int8Array(n), cx = new Float32Array(n);
    var c1 = 0, c2 = 0, c3 = 0, i, k;
    for (i = 0; i < n; i++) {
      var x0 = P.getX(i) * 1000, y0 = P.getY(i) * 1000, z0 = P.getZ(i) * 1000;
      var h = HOLES[0];
      for (k = 1; k < 4; k++) if (Math.abs(x0 - HOLES[k]) < Math.abs(x0 - h)) h = HOLES[k];
      var r0 = Math.hypot(x0 - h, z0);
      cx[i] = h;
      if (r0 > 3.9 && r0 < 4.1 && Math.abs(y0 - 1.0) < 0.003) { ring[i] = 3; c3++; }
      else if (r0 < 2.6 && Math.abs(y0 - 0.1615) < 0.01) { ring[i] = 2; c2++; }
      else if (r0 < 2.6 && Math.abs(y0 - 0.079) < 0.006) { ring[i] = 1; c1++; }
    }
    var holes = c1 > 0 && c1 === c2 && c2 === c3;
    var rD = 2.5476, dr = Rt - rD, depth = dr / Math.tan(half), yc = T - depth;
    var nl = Math.hypot(depth, dr), ny = dr / nl, nr = -depth / nl;

    /* cone triangles get their own copies of the top-edge vertices, so the edge is crisp */
    var dup = new Map(), newIdx = new Uint32Array(idx.length), extra = 0;
    for (var t = 0; t < idx.length; t += 3) {
      var tri = [idx[t], idx[t + 1], idx[t + 2]];
      var cone = holes && (ring[tri[0]] === 2 || ring[tri[1]] === 2 || ring[tri[2]] === 2) &&
                          (ring[tri[0]] === 3 || ring[tri[1]] === 3 || ring[tri[2]] === 3);
      for (k = 0; k < 3; k++) {
        var v = tri[k];
        if (cone && ring[v] === 3) {
          if (!dup.has(v)) dup.set(v, n + extra++);
          newIdx[t + k] = dup.get(v);
        } else newIdx[t + k] = v;
      }
    }
    var m = n + extra;
    var pos = new Float32Array(m * 3), nor = new Float32Array(m * 3), uv = new Float32Array(m * 2);
    for (i = 0; i < n; i++) {
      var x = P.getX(i) * 1000, y = P.getY(i) * 1000, z = P.getZ(i) * 1000;
      var nx = Nn.getX(i), nyy = Nn.getY(i), nz = Nn.getZ(i);
      var r = Math.hypot(x - cx[i], z) || 1, ux = (x - cx[i]) / r, uz = z / r;
      if (holes && ring[i] === 3) { x = cx[i] + ux * Rt; z = uz * Rt; y = T; }
      else if (holes && ring[i] === 2) { y = yc; nx = ux * nr; nyy = ny; nz = uz * nr; }
      else if (holes && ring[i] === 1) { y = yc - 0.0825; }
      else if (y > 0.5) y += T - 1;
      pos[i * 3] = x / 1000; pos[i * 3 + 1] = y / 1000; pos[i * 3 + 2] = z / 1000;
      nor[i * 3] = nx; nor[i * 3 + 1] = nyy; nor[i * 3 + 2] = nz;
      if (UV) { uv[i * 2] = UV.getX(i); uv[i * 2 + 1] = UV.getY(i); }
    }
    dup.forEach(function (j, i2) {
      pos[j * 3] = pos[i2 * 3]; pos[j * 3 + 1] = pos[i2 * 3 + 1]; pos[j * 3 + 2] = pos[i2 * 3 + 2];
      var xx = pos[i2 * 3] * 1000, zz = pos[i2 * 3 + 2] * 1000, rr = Math.hypot(xx - cx[i2], zz) || 1;
      nor[j * 3] = (xx - cx[i2]) / rr * nr; nor[j * 3 + 1] = ny; nor[j * 3 + 2] = zz / rr * nr;
      uv[j * 2] = uv[i2 * 2]; uv[j * 2 + 1] = uv[i2 * 2 + 1];
    });
    var g = new THREE.BufferGeometry();
    g.setAttribute('position', new THREE.BufferAttribute(pos, 3));
    g.setAttribute('normal', new THREE.BufferAttribute(nor, 3));
    if (UV) g.setAttribute('uv', new THREE.BufferAttribute(uv, 2));
    g.setIndex(new THREE.BufferAttribute(newIdx, 1));
    g.computeBoundingSphere();
    g.computeBoundingBox();
    return { geometry: g, holes: holes, yc: holes ? yc : 0.08, Rt: holes ? Rt : 4.0 };
  };

  /* ---- nav: solid once the page moves; seven items from 1000 px up, the menu below (base.css, PLAN.md §3.8) ----
     KNOBS 'nav' news: false takes the News item out of the bar; the footers and the timeline still link the page, and
     the bar still collapses to the menu below 1000 px. The menu closes itself if the window widens past the collapse. */
  var NAV = BMH.knobs('nav', { news: true });
  var navEl = document.querySelector('.nav');
  if (navEl && NAV.news === false) {
    var newsA = navEl.querySelector('.nav__links a[href="news.html"]');
    if (newsA && newsA.parentNode && newsA.parentNode.tagName === 'LI') newsA.parentNode.remove();
  }
  document.addEventListener('DOMContentLoaded', function () {
    var nav = document.querySelector('.nav');
    if (!nav) return;
    BMH.onScroll(function (st) { nav.classList.toggle('is-scrolled', st.y > 8); });
    var btn = nav.querySelector('.nav__menu');
    if (!btn) return;
    btn.addEventListener('click', function () {
      var open = nav.classList.toggle('is-open');
      btn.setAttribute('aria-expanded', open ? 'true' : 'false');
    });
    var wide = window.matchMedia('(min-width: 1000px)');
    var onWide = function () {
      if (!wide.matches || !nav.classList.contains('is-open')) return;
      nav.classList.remove('is-open');
      btn.setAttribute('aria-expanded', 'false');
    };
    if (wide.addEventListener) wide.addEventListener('change', onWide);
    else if (wide.addListener) wide.addListener(onWide);
  });
})();
